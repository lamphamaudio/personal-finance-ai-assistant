create table if not exists public.app_seen_transactions (
    tx_id text primary key,
    source text not null,
    seen_at timestamptz not null
);

create table if not exists public.app_tx_history (
    tx_id text primary key,
    date date not null,
    clean_name text not null,
    amount numeric not null,
    category text not null default 'Chưa phân loại',
    original_description text not null default ''
);

create table if not exists public.app_user_overrides (
    original_description text primary key,
    category text not null,
    clean_name text not null
);

create table if not exists public.app_merchant_categories (
    clean_name text primary key,
    category text not null
);

create table if not exists public.app_budget_limits (
    category text primary key,
    monthly_limit numeric not null
);

create table if not exists public.app_settings (
    key text primary key,
    value text not null
);

create table if not exists public.app_category_rules (
    id bigint generated by default as identity primary key,
    rule_type text not null,
    pattern text not null,
    category text not null,
    priority integer not null default 100,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.app_learning_feedback (
    id bigint generated by default as identity primary key,
    tx_id text,
    original_description text not null default '',
    clean_name text not null,
    category text not null,
    source text not null,
    apply_to_future boolean not null default true,
    created_at timestamptz not null default now()
);

